CREATE PROCEDURE "TEST_JUNIO_2026"."SpPdxMTTOConsultaSolicitudesCompraMP" (
    IN P_FILTRO_ORDEN        NVARCHAR(50),
    IN P_FILTRO_FECHA_INICIO DATE,
    IN P_FILTRO_FECHA_FIN    DATE,
    IN P_FILTRO_PLANTA       NVARCHAR(10)  -- ⬅️ viene de SR
)
LANGUAGE SQLSCRIPT
SQL SECURITY INVOKER
AS
BEGIN
    SELECT
        -- Datos de la Solicitud de Compra
        SC."ID_SOLICITUD_COMPRA",
        SC."ID_SOLICITUD_REFACCION",
        SC."COMENTARIOS",
        TO_VARCHAR(SC."FECHA_SOLICITUD", 'DD/MM/YYYY HH24:MI:SS') AS "FECHA_SOLICITUD",
        SC."ESTATUS",
        SC."USUARIO_SOLICITA",
        SC."USUARIO_ATIENDE",
        TO_VARCHAR(SC."FECHA_ATENCION", 'DD/MM/YYYY HH24:MI:SS')  AS "FECHA_ATENCION",
        -- Datos heredados de la Solicitud de Refacción
        SR."ORDEN_TRABAJO",
        SR."ID_EQUIPO",
        SR."REFACCION_SOLICITADA",
        SR."CANTIDAD",
        SR."NIVEL_URGENCIA",
        SR."DESCRIPCION_NECESIDAD",
        SR."PLANTA"
    FROM "TEST_JUNIO_2026"."PdxMTTOMPSolicitudCompraMP" SC
    INNER JOIN "TEST_JUNIO_2026"."PdxMTTOMPSolicitudRefacciones" SR
        ON SC."ID_SOLICITUD_REFACCION" = SR."ID_SOLICITUD"
    WHERE
        (:P_FILTRO_ORDEN  IS NULL OR SR."ORDEN_TRABAJO" = :P_FILTRO_ORDEN)
        AND (:P_FILTRO_PLANTA IS NULL OR SR."PLANTA"    = :P_FILTRO_PLANTA)  -- ⬅️ filtro por SR
        AND (
            :P_FILTRO_FECHA_INICIO IS NULL
            OR :P_FILTRO_FECHA_FIN IS NULL
            OR CAST(SC."FECHA_SOLICITUD" AS DATE) BETWEEN :P_FILTRO_FECHA_INICIO AND :P_FILTRO_FECHA_FIN
        )
    ORDER BY
        SC."FECHA_SOLICITUD" DESC;
END;

