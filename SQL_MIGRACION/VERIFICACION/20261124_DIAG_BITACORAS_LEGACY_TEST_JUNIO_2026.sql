-- (0b) Muestras de como estan guardadas las OT (para confirmar el formato)
SELECT TOP 10 'PVC' AS PROCESO, "ID_REGISTRO", TO_VARCHAR("FECHA", 'YYYY-MM-DD') AS FECHA, "LINEA",
       TO_NVARCHAR("OTMP") AS OTMP, TO_NVARCHAR("OTMC") AS OTMC, "MANTENIMIENTO_PREVENTIVO" AS MP
FROM "TEST_JUNIO_2026"."PdxMTTOTiemposMuertosProduccionPVC"
WHERE IFNULL("ESTATUS", 'A') = 'A' AND "FECHA" BETWEEN '2026-11-01' AND '2026-11-30'
