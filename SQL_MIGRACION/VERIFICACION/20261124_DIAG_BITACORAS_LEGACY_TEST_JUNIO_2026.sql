-- (1) Resumen preventivos PVC
SELECT 'PVC' AS PROCESO,
       COUNT(DISTINCT TM."ID_REGISTRO") AS FILAS_CON_OTMP,
       COUNT(DISTINCT TRIM(MPG."NUMERO_ORDEN")) AS OTMP_DISTINTAS,
       COUNT(DISTINCT CASE WHEN OT."HORA_FIN" IS NOT NULL
                            AND CAST(OT."HORA_FIN" AS DATE) <> CAST(TM."FECHA" AS DATE)
                           THEN TRIM(MPG."NUMERO_ORDEN") END) AS OTMP_FECHA_DISTINTA,
       COUNT(DISTINCT CASE WHEN OT."HORA_FIN" IS NULL
                           THEN TRIM(MPG."NUMERO_ORDEN") END) AS OTMP_SIN_HORA_FIN,
       COUNT(DISTINCT CASE WHEN OT."FIRMA_REALIZO"       IS NULL OR LENGTH(TRIM(OT."FIRMA_REALIZO"))       = 0
                             OR OT."FIRMA_SUPERVISO"     IS NULL OR LENGTH(TRIM(OT."FIRMA_SUPERVISO"))     = 0
                             OR OT."FIRMA_MANTENIMIENTO" IS NULL OR LENGTH(TRIM(OT."FIRMA_MANTENIMIENTO")) = 0
                           THEN TRIM(MPG."NUMERO_ORDEN") END) AS OTMP_SIN_3_FIRMAS
FROM "TEST_JUNIO_2026"."PdxMTTOTiemposMuertosProduccionPVC" TM
JOIN "TEST_JUNIO_2026"."PdxMTTOMPGenerados" MPG
  ON LOCATE(TO_NVARCHAR(TM."OTMP"), '"' || TRIM(MPG."NUMERO_ORDEN") || '"') > 0
LEFT JOIN "TEST_JUNIO_2026"."PdxMTTOOrdenesTrabajoMP" OT
  ON OT."NUMERO_ORDEN" = MPG."NUMERO_ORDEN"
WHERE IFNULL(TM."ESTATUS", 'A') = 'A'
  AND TO_NVARCHAR(TM."OTMP") LIKE '%OTMP-%';
-- @@

-- (2) Preventivos desfasados PVC (fila distinta al dia de cierre del tecnico)
SELECT TOP 300 TM."ID_REGISTRO", TO_VARCHAR(TM."FECHA", 'YYYY-MM-DD') AS FECHA_FILA, TM."LINEA",
       TRIM(MPG."NUMERO_ORDEN")                                     AS ORDEN,
       TO_VARCHAR(OT."HORA_INICIO", 'YYYY-MM-DD HH24:MI')            AS INICIO_TECNICO,
       TO_VARCHAR(OT."HORA_FIN", 'YYYY-MM-DD HH24:MI')               AS FIN_TECNICO,
       TO_VARCHAR(MPG."HORA_APERTURA", 'YYYY-MM-DD HH24:MI')         AS APERTURA_SISTEMA,
       TO_VARCHAR(SR."FECHA_REAL_INICIO", 'YYYY-MM-DD')              AS FECHA_REPROGRAMADA,
       CASE WHEN OT."FIRMA_REALIZO"       IS NOT NULL AND LENGTH(TRIM(OT."FIRMA_REALIZO"))       > 0
             AND OT."FIRMA_SUPERVISO"     IS NOT NULL AND LENGTH(TRIM(OT."FIRMA_SUPERVISO"))     > 0
             AND OT."FIRMA_MANTENIMIENTO" IS NOT NULL AND LENGTH(TRIM(OT."FIRMA_MANTENIMIENTO")) > 0
            THEN 'SI' ELSE 'NO' END                                  AS TRES_FIRMAS,
       (SELECT MAX(T2."ID_REGISTRO")
          FROM "TEST_JUNIO_2026"."PdxMTTOTiemposMuertosProduccionPVC" T2
         WHERE IFNULL(T2."ESTATUS", 'A') = 'A'
           AND T2."ID_REGISTRO" <> TM."ID_REGISTRO"
           AND CAST(T2."FECHA" AS DATE) = CAST(OT."HORA_FIN" AS DATE)
           AND T2."LINEA" = TM."LINEA")                              AS ID_FILA_DESTINO
FROM "TEST_JUNIO_2026"."PdxMTTOTiemposMuertosProduccionPVC" TM
JOIN "TEST_JUNIO_2026"."PdxMTTOMPGenerados" MPG
  ON LOCATE(TO_NVARCHAR(TM."OTMP"), '"' || TRIM(MPG."NUMERO_ORDEN") || '"') > 0
LEFT JOIN "TEST_JUNIO_2026"."PdxMTTOOrdenesTrabajoMP" OT
  ON OT."NUMERO_ORDEN" = MPG."NUMERO_ORDEN"
LEFT JOIN (
    SELECT "NUMERO_ORDEN", MAX("FECHA_REAL_INICIO") AS "FECHA_REAL_INICIO"
    FROM "TEST_JUNIO_2026"."PdxMTTOSolicitudesReprogramacion"
    WHERE "ESTATUS" <> 'Rechazada'
    GROUP BY "NUMERO_ORDEN"
) SR ON SR."NUMERO_ORDEN" = MPG."NUMERO_ORDEN"
WHERE IFNULL(TM."ESTATUS", 'A') = 'A'
  AND OT."HORA_FIN" IS NOT NULL
  AND CAST(OT."HORA_FIN" AS DATE) <> CAST(TM."FECHA" AS DATE)
ORDER BY TM."FECHA", TM."LINEA", ORDEN;
-- @@

