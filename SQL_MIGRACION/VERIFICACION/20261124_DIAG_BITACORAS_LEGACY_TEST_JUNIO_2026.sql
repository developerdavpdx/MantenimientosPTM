-- (0) Chequeo de FORMATO: filas que traen texto de OT vs filas con el formato
--     JSON que espera el saneo ('"OTMP-xxx"'). Si FILAS_CON_TEXTO > FILAS_JSON,
--     hay OT guardadas en otro formato y el saneo no las reconoceria.
SELECT 'PVC' AS PROCESO,
       COUNT(CASE WHEN TO_NVARCHAR("OTMP") LIKE '%OTMP-%' THEN 1 END) AS FILAS_CON_TEXTO_OTMP,
       COUNT(CASE WHEN TO_NVARCHAR("OTMP") LIKE '%"OTMP-%' THEN 1 END) AS FILAS_JSON_OTMP,
       COUNT(CASE WHEN TO_NVARCHAR("OTMC") LIKE '%OTMC-%' THEN 1 END) AS FILAS_CON_TEXTO_OTMC,
       COUNT(CASE WHEN TO_NVARCHAR("OTMC") LIKE '%"OTMC-%' THEN 1 END) AS FILAS_JSON_OTMC
FROM "TEST_JUNIO_2026"."PdxMTTOTiemposMuertosProduccionPVC"
WHERE IFNULL("ESTATUS", 'A') = 'A' AND "FECHA" BETWEEN '2026-11-01' AND '2026-11-30'
UNION ALL
SELECT 'PEADLISO',
       COUNT(CASE WHEN TO_NVARCHAR("OTMP") LIKE '%OTMP-%' THEN 1 END),
       COUNT(CASE WHEN TO_NVARCHAR("OTMP") LIKE '%"OTMP-%' THEN 1 END),
       COUNT(CASE WHEN TO_NVARCHAR("OTMC") LIKE '%OTMC-%' THEN 1 END),
       COUNT(CASE WHEN TO_NVARCHAR("OTMC") LIKE '%"OTMC-%' THEN 1 END)
FROM "TEST_JUNIO_2026"."PdxMTTOTiemposMuertosProduccionPeadLiso"
WHERE IFNULL("ESTATUS", 'A') = 'A' AND "FECHA" BETWEEN '2026-11-01' AND '2026-11-30'
UNION ALL
SELECT 'CORRUGADO',
       COUNT(CASE WHEN TO_NVARCHAR("OTMP") LIKE '%OTMP-%' THEN 1 END),
       COUNT(CASE WHEN TO_NVARCHAR("OTMP") LIKE '%"OTMP-%' THEN 1 END),
       COUNT(CASE WHEN TO_NVARCHAR("OTMC") LIKE '%OTMC-%' THEN 1 END),
       COUNT(CASE WHEN TO_NVARCHAR("OTMC") LIKE '%"OTMC-%' THEN 1 END)
FROM "TEST_JUNIO_2026"."PdxMTTOTiemposMuertosProduccionCorrugado"
WHERE IFNULL("ESTATUS", 'A') = 'A' AND "FECHA" BETWEEN '2026-11-01' AND '2026-11-30'
UNION ALL
SELECT 'INY',
       COUNT(CASE WHEN TO_NVARCHAR("OTMP") LIKE '%OTMP-%' THEN 1 END),
       COUNT(CASE WHEN TO_NVARCHAR("OTMP") LIKE '%"OTMP-%' THEN 1 END),
       COUNT(CASE WHEN TO_NVARCHAR("OTMC") LIKE '%OTMC-%' THEN 1 END),
       COUNT(CASE WHEN TO_NVARCHAR("OTMC") LIKE '%"OTMC-%' THEN 1 END)
FROM "TEST_JUNIO_2026"."PdxMTTOTiemposMuertosProduccionINY"
WHERE IFNULL("ESTATUS", 'A') = 'A' AND "FECHA" BETWEEN '2026-11-01' AND '2026-11-30';
