-- ============================================================================
-- 2026-11-24 - DIAGNOSTICO (solo lectura) de bitacoras LEGACY en TEST_JUNIO_2026
--
-- Objetivo: medir el desfase historico entre la fecha de la fila de bitacora y
-- la fecha en que el tecnico realmente cerro la OT (HORA_FIN), antes de decidir
-- el saneamiento.
--
-- NO MODIFICA NADA. Solo SELECT.
--
-- Regla nueva (ya aplicada en el front desde el 24/11/2026):
--   fila del preventivo = HORA_FIN del tecnico || FECHA_REAL_INICIO || HORA_APERTURA
--   fila del correctivo = HORA_APERTURA (FechaCreacion)  <-- PENDIENTE DE DEFINIR
--   preventivos solo con 3 firmas / correctivos solo con 2 firmas
--
-- Salidas por proceso (PVC, PEADLISO, CORRUGADO, INY):
--   (1) Resumen: cuantas OTMP/OTMC hay en bitacora, cuantas estan desfasadas
--       respecto a HORA_FIN y cuantas no tienen las firmas completas.
--   (2) Detalle de preventivos desfasados (con la fila destino si ya existe).
--   (3) Detalle de correctivos desfasados.
--
-- Nota HANA: LOCATE(<texto>, <subtexto>) -> el texto completo va primero.
--   (al reves que en otros motores)
-- ============================================================================


-- ############################################################################
-- PVC
