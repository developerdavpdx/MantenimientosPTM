-- Verificacion post-saneo (23/11/2026): en las bitacoras NO debe quedar ninguna
-- OT correctiva donde la maquina NO estuvo detenida.
-- Resultado esperado tras el saneamiento: ORDENES_SIN_PARO = 0 y ORDENES_HUERFANAS = 0
-- en los 4 procesos. ORDENES_CON_PARO son las OTs reales registradas en bitacora.
--
-- Si alguna tabla da ORDENES_SIN_PARO > 0, el segundo SELECT lista las infractoras.

SELECT 'PVC' AS PROCESO,
       COUNT(CASE WHEN IFNULL(OT."MAQUINA_DETENIDA",0) = 1 THEN 1 END) AS ORDENES_CON_PARO,
       COUNT(CASE WHEN IFNULL(OT."MAQUINA_DETENIDA",0) = 0 THEN 1 END) AS ORDENES_SIN_PARO,
       COUNT(CASE WHEN OT."NUMERO_ORDEN" IS NULL THEN 1 END) AS ORDENES_HUERFANAS
FROM "PTM_2022_FINAL"."PdxMTTOTiemposMuertosProduccionPVC" TM
JOIN "PTM_2022_FINAL"."PdxMTTOMCGenerados" MCG ON TM."OTMC" LIKE '%"' || MCG."NUMERO_ORDEN" || '"%'
LEFT JOIN "PTM_2022_FINAL"."PdxMTTOOrdenesTrabajoMC" OT ON OT."NUMERO_ORDEN" = MCG."NUMERO_ORDEN"
WHERE IFNULL(TM."ESTATUS",'A') = 'A'
UNION ALL
SELECT 'PEADLISO',
       COUNT(CASE WHEN IFNULL(OT."MAQUINA_DETENIDA",0) = 1 THEN 1 END),
       COUNT(CASE WHEN IFNULL(OT."MAQUINA_DETENIDA",0) = 0 THEN 1 END),
       COUNT(CASE WHEN OT."NUMERO_ORDEN" IS NULL THEN 1 END)
FROM "PTM_2022_FINAL"."PdxMTTOTiemposMuertosProduccionPeadLiso" TM
JOIN "PTM_2022_FINAL"."PdxMTTOMCGenerados" MCG ON TM."OTMC" LIKE '%"' || MCG."NUMERO_ORDEN" || '"%'
LEFT JOIN "PTM_2022_FINAL"."PdxMTTOOrdenesTrabajoMC" OT ON OT."NUMERO_ORDEN" = MCG."NUMERO_ORDEN"
WHERE IFNULL(TM."ESTATUS",'A') = 'A'
UNION ALL
SELECT 'CORRUGADO',
       COUNT(CASE WHEN IFNULL(OT."MAQUINA_DETENIDA",0) = 1 THEN 1 END),
       COUNT(CASE WHEN IFNULL(OT."MAQUINA_DETENIDA",0) = 0 THEN 1 END),
       COUNT(CASE WHEN OT."NUMERO_ORDEN" IS NULL THEN 1 END)
FROM "PTM_2022_FINAL"."PdxMTTOTiemposMuertosProduccionCorrugado" TM
JOIN "PTM_2022_FINAL"."PdxMTTOMCGenerados" MCG ON TM."OTMC" LIKE '%"' || MCG."NUMERO_ORDEN" || '"%'
LEFT JOIN "PTM_2022_FINAL"."PdxMTTOOrdenesTrabajoMC" OT ON OT."NUMERO_ORDEN" = MCG."NUMERO_ORDEN"
WHERE IFNULL(TM."ESTATUS",'A') = 'A'
UNION ALL
SELECT 'INY',
       COUNT(CASE WHEN IFNULL(OT."MAQUINA_DETENIDA",0) = 1 THEN 1 END),
       COUNT(CASE WHEN IFNULL(OT."MAQUINA_DETENIDA",0) = 0 THEN 1 END),
       COUNT(CASE WHEN OT."NUMERO_ORDEN" IS NULL THEN 1 END)
FROM "PTM_2022_FINAL"."PdxMTTOTiemposMuertosProduccionINY" TM
JOIN "PTM_2022_FINAL"."PdxMTTOMCGenerados" MCG ON TM."OTMC" LIKE '%"' || MCG."NUMERO_ORDEN" || '"%'
LEFT JOIN "PTM_2022_FINAL"."PdxMTTOOrdenesTrabajoMC" OT ON OT."NUMERO_ORDEN" = MCG."NUMERO_ORDEN"
WHERE IFNULL(TM."ESTATUS",'A') = 'A';

-- Detalle de infractoras (solo relevante si el resumen anterior dio algo > 0)
SELECT 'PVC' AS PROCESO, TM."ID_REGISTRO", TM."FECHA", TM."LINEA", MCG."NUMERO_ORDEN",
       IFNULL(OT."MAQUINA_DETENIDA",0) AS MAQUINA_DETENIDA
FROM "PTM_2022_FINAL"."PdxMTTOTiemposMuertosProduccionPVC" TM
JOIN "PTM_2022_FINAL"."PdxMTTOMCGenerados" MCG ON TM."OTMC" LIKE '%"' || MCG."NUMERO_ORDEN" || '"%'
LEFT JOIN "PTM_2022_FINAL"."PdxMTTOOrdenesTrabajoMC" OT ON OT."NUMERO_ORDEN" = MCG."NUMERO_ORDEN"
WHERE IFNULL(TM."ESTATUS",'A') = 'A' AND IFNULL(OT."MAQUINA_DETENIDA",0) = 0
UNION ALL
SELECT 'PEADLISO', TM."ID_REGISTRO", TM."FECHA", TM."LINEA", MCG."NUMERO_ORDEN", IFNULL(OT."MAQUINA_DETENIDA",0)
FROM "PTM_2022_FINAL"."PdxMTTOTiemposMuertosProduccionPeadLiso" TM
JOIN "PTM_2022_FINAL"."PdxMTTOMCGenerados" MCG ON TM."OTMC" LIKE '%"' || MCG."NUMERO_ORDEN" || '"%'
LEFT JOIN "PTM_2022_FINAL"."PdxMTTOOrdenesTrabajoMC" OT ON OT."NUMERO_ORDEN" = MCG."NUMERO_ORDEN"
WHERE IFNULL(TM."ESTATUS",'A') = 'A' AND IFNULL(OT."MAQUINA_DETENIDA",0) = 0
UNION ALL
SELECT 'CORRUGADO', TM."ID_REGISTRO", TM."FECHA", TM."LINEA", MCG."NUMERO_ORDEN", IFNULL(OT."MAQUINA_DETENIDA",0)
FROM "PTM_2022_FINAL"."PdxMTTOTiemposMuertosProduccionCorrugado" TM
JOIN "PTM_2022_FINAL"."PdxMTTOMCGenerados" MCG ON TM."OTMC" LIKE '%"' || MCG."NUMERO_ORDEN" || '"%'
LEFT JOIN "PTM_2022_FINAL"."PdxMTTOOrdenesTrabajoMC" OT ON OT."NUMERO_ORDEN" = MCG."NUMERO_ORDEN"
WHERE IFNULL(TM."ESTATUS",'A') = 'A' AND IFNULL(OT."MAQUINA_DETENIDA",0) = 0
UNION ALL
SELECT 'INY', TM."ID_REGISTRO", TM."FECHA", TM."LINEA", MCG."NUMERO_ORDEN", IFNULL(OT."MAQUINA_DETENIDA",0)
FROM "PTM_2022_FINAL"."PdxMTTOTiemposMuertosProduccionINY" TM
JOIN "PTM_2022_FINAL"."PdxMTTOMCGenerados" MCG ON TM."OTMC" LIKE '%"' || MCG."NUMERO_ORDEN" || '"%'
LEFT JOIN "PTM_2022_FINAL"."PdxMTTOOrdenesTrabajoMC" OT ON OT."NUMERO_ORDEN" = MCG."NUMERO_ORDEN"
WHERE IFNULL(TM."ESTATUS",'A') = 'A' AND IFNULL(OT."MAQUINA_DETENIDA",0) = 0;
