CREATE OR REPLACE PROCEDURE "DBADMIN"."SpPdxMTTOConsultarTiemposMuertosCorrugado"(
    IN p_FECHA_INICIO DATE,
    IN p_FECHA_FIN DATE,
    IN p_LINEA NVARCHAR(20),
    IN p_PLANTA INT,
    IN p_TURNO NVARCHAR(5),       --    NUEVO
    IN p_PRODUCTO NVARCHAR(50)    --    NUEVO
)
LANGUAGE SQLSCRIPT
SQL SECURITY INVOKER
AS
BEGIN
SELECT
    "ID_REGISTRO",
    -- DATOS GENERALES
    "MES",
    "FECHA",
    "LINEA",
    "CORRUGADOR",
    "PRODUCTO",
    "TURNO",
    "GRUPO",
    "COMENTARIOS",
    "OTMC",
    "OTMP",
    "ID_PRODUCTO_TERMINADO",
    "PESO_MINIMO",
    "TRLIBERADOS",
    "PRODUCCION_NETA",
    "PESO_ESTANDAR",
    "PORCENTAJE_SOBREPESO",
    "SCRAP_SIN_CORTE_SIERRA",
    "SCRAP_CORTE_SIERRA",
    "SCRAP_TOTAL",
    "PORCENTAJE_SCRAP_SIN_CORTE",
    "PORCENTAJE_SCRAP_CORTE",
    "KG_REPROCESO",
    "CARBONATO",
    "HORAS_PROGRAMADAS",
    -- TIEMPO NO DISPONIBLE
    "MANTENIMIENTO_PREVENTIVO",
    "CONTROL_INVENTARIOS",
    "FALTA_ENERGIA",
    "FALTA_MATERIA_PRIMA",
    "PREPARACION_CAMBIO",
    "ARRANQUE_ESTABILIZACION",
    "TIEMPO_MTTO_CORRECTIVOS_ARRANQUE",
    -- TIEMPO NO PRODUCTIVO
    "TIEMPO_MUERTO_CORRECTIVOS",
    "TIEMPO_MUERTO_HERRAMENTALES",
    "CAMBIO_MOLDE_SETUP_EXCESOS",
    "TIEMPO_MUERTO_ARRANCAR",
    "TIEMPO_MUERTO_PROCESO",
    -- KPIs
    "TIEMPO_DISPONIBLE",
    "TIEMPO_PRODUCTIVO",
        -- NUEVO
    "KG_HR_LINEA",
    "KG_HR_PRODUCTO",
    "OBJETIVO_EFICIENCIA",
    "DISPONIBILIDAD_PORCENTAJE",
    "KG_POR_TIEMPO_DISPONIBLE",
    "KG_NETOS_HR_REALES",
    "PORCENTAJE_RENDIMIENTO",
    "PORCENTAJE_CALIDAD",
    "PORCENTAJE_OEE",
    "PORCENTAJE_EFICIENCIA_PRODUCTO",
    "EFICIENCIA_OPERATIVA",
    -- AUDITOR-A
    "USUARIO",
    "PLANTA",
    "FECHA_CREACION",
    "FECHA_ACTUALIZACION"
FROM "PdxMTTOTiemposMuertosProduccionCorrugado"
WHERE
    (
        :p_FECHA_INICIO IS NULL
        OR :p_FECHA_FIN IS NULL
        OR CAST("FECHA" AS DATE)
           BETWEEN :p_FECHA_INICIO AND :p_FECHA_FIN
    )
    AND (
        :p_LINEA IS NULL
        OR :p_LINEA = ''
        OR "LINEA" = :p_LINEA
    )
    AND (
        :p_PLANTA IS NULL
        OR "PLANTA" = :p_PLANTA
    )
    -- NUEVO: Filtro Turno
    AND (
        :p_TURNO IS NULL
        OR :p_TURNO = ''
        OR "TURNO" = :p_TURNO
    )
    -- NUEVO: Filtro Producto con LIKE
    AND (
        :p_PRODUCTO IS NULL
        OR :p_PRODUCTO = ''
        OR "PRODUCTO" LIKE '%' || :p_PRODUCTO || '%'
    )
    AND IFNULL("ESTATUS", 'A') = 'A'
ORDER BY
    TO_INT(SUBSTRING_REGEXPR('[0-9]+' IN "LINEA")),
    "FECHA",
    "TURNO",
    "GRUPO";
END;
