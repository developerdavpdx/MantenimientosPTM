CREATE COLUMN TABLE "DBADMIN"."TMP_SANEO_PVC_MAP_20261124" AS (
SELECT 'P' AS TIPO, TRIM(MPG."NUMERO_ORDEN") AS ORDEN, TM."ID_REGISTRO" AS ID_FILA_ORIGEN,
       TO_NVARCHAR(TM."PLANTA") AS PLANTA, TM."LINEA" AS LINEA,
       CAST(TM."FECHA" AS DATE) AS FECHA_ORIGEN,
       CASE WHEN CAST(OT."HORA_FIN" AS DATE) BETWEEN '2026-11-01' AND '2026-11-30'
            THEN CAST(OT."HORA_FIN" AS DATE) ELSE CAST(TM."FECHA" AS DATE) END AS FECHA_DESTINO,
       ROUND(IFNULL(OT."DURACION_HRS", 0), 4) AS HORAS,
       0 AS ES_HERR,
       CASE WHEN LENGTH(TRIM(OT."FIRMA_REALIZO"))       > 0
             AND LENGTH(TRIM(OT."FIRMA_SUPERVISO"))     > 0
             AND LENGTH(TRIM(OT."FIRMA_MANTENIMIENTO")) > 0
