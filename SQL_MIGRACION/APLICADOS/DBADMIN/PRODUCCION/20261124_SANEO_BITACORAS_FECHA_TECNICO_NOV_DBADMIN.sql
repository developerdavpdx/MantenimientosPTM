CREATE COLUMN TABLE "DBADMIN"."TMP_SANEO_PVC_STAGE_20261124" AS (
SELECT T."ID_REGISTRO",
       TO_VARCHAR(T."FECHA", 'YYYY-MM-DD') AS FECHA,
       T."LINEA",
       ARR.OTMP, ARR.OTMC,
       IFNULL(ARR.MP, 0)   AS MP_EXACTO,
       IFNULL(ARR.MTTO, 0) AS MTTO_EXACTO,
       IFNULL(ARR.HERR, 0) AS HERR_EXACTO,
       CASE WHEN LENGTH(IFNULL(TO_NVARCHAR(T."OTMP"), '')) < 3 THEN 0
            ELSE (LENGTH(TO_NVARCHAR(T."OTMP")) - LENGTH(REPLACE(TO_NVARCHAR(T."OTMP"), '"OT', ''))) / 3 END AS OLD_P,
       CASE WHEN LENGTH(IFNULL(TO_NVARCHAR(T."OTMC"), '')) < 3 THEN 0
            ELSE (LENGTH(TO_NVARCHAR(T."OTMC")) - LENGTH(REPLACE(TO_NVARCHAR(T."OTMC"), '"OT', ''))) / 3 END AS OLD_C,
       IFNULL(MAPC.N_P, 0) AS MAP_P,
       IFNULL(MAPC.N_C, 0) AS MAP_C,
       IFNULL(DUP.N, 0)    AS DUP_FILAS
FROM "DBADMIN"."PdxMTTOTiemposMuertosProduccionPVC" T
JOIN "DBADMIN"."TMP_SANEO_PVC_AFECT_20261124" A ON A.ID_REGISTRO = T."ID_REGISTRO"
LEFT JOIN (
    SELECT D.PLANTA, D.LINEA, D.FECHA_DESTINO,
           CASE WHEN COUNT(CASE WHEN D.TIPO = 'P' THEN 1 END) = 0 THEN NULL
                ELSE '[' || STRING_AGG(CASE WHEN D.TIPO = 'P' THEN '"' || D.ORDEN || '"' END, ',' ORDER BY D.ORDEN) || ']' END AS OTMP,
           CASE WHEN COUNT(CASE WHEN D.TIPO = 'C' THEN 1 END) = 0 THEN NULL
                ELSE '[' || STRING_AGG(CASE WHEN D.TIPO = 'C' THEN '"' || D.ORDEN || '"' END, ',' ORDER BY D.ORDEN) || ']' END AS OTMC,
           SUM(CASE WHEN D.TIPO = 'P' THEN D.HORAS ELSE 0 END) AS MP,
           SUM(CASE WHEN D.TIPO = 'C' AND D.ES_HERR = 0 THEN D.HORAS ELSE 0 END) AS MTTO,
           SUM(CASE WHEN D.TIPO = 'C' AND D.ES_HERR = 1 THEN D.HORAS ELSE 0 END) AS HERR
    FROM (
        SELECT PLANTA, LINEA, FECHA_DESTINO, TIPO, ORDEN, MAX(HORAS) AS HORAS, MAX(ES_HERR) AS ES_HERR
        FROM "DBADMIN"."TMP_SANEO_PVC_MAP_20261124"
        WHERE INCLUIR = 1
        GROUP BY PLANTA, LINEA, FECHA_DESTINO, TIPO, ORDEN
    ) D
    GROUP BY D.PLANTA, D.LINEA, D.FECHA_DESTINO
) ARR ON ARR.PLANTA = TO_NVARCHAR(T."PLANTA") AND ARR.LINEA = T."LINEA" AND ARR.FECHA_DESTINO = CAST(T."FECHA" AS DATE)
LEFT JOIN (
    SELECT ID_FILA_ORIGEN,
           SUM(CASE WHEN TIPO = 'P' THEN 1 ELSE 0 END) AS N_P,
           SUM(CASE WHEN TIPO = 'C' THEN 1 ELSE 0 END) AS N_C
    FROM "DBADMIN"."TMP_SANEO_PVC_MAP_20261124"
    GROUP BY ID_FILA_ORIGEN
) MAPC ON MAPC.ID_FILA_ORIGEN = T."ID_REGISTRO"
LEFT JOIN (
    SELECT TO_NVARCHAR("PLANTA") AS PLANTA, "LINEA", CAST("FECHA" AS DATE) AS FECHA, COUNT(*) AS N
    FROM "DBADMIN"."PdxMTTOTiemposMuertosProduccionPVC"
    WHERE IFNULL("ESTATUS", 'A') = 'A' AND "FECHA" BETWEEN '2026-11-01' AND '2026-11-30'
      AND "ID_PRODUCTO_TERMINADO" IS NULL
      AND (IFNULL(TO_NVARCHAR("PRODUCTO"), '') = '' AND IFNULL("TURNO", '') = ''
           OR IFNULL(LENGTH(TO_NVARCHAR("OTMP")), 0) > 2
           OR IFNULL(LENGTH(TO_NVARCHAR("OTMC")), 0) > 2
           OR IFNULL(LENGTH(TO_NVARCHAR("ID_PARO")), 0) > 0)
    GROUP BY TO_NVARCHAR("PLANTA"), "LINEA", CAST("FECHA" AS DATE)
) DUP ON DUP.PLANTA = TO_NVARCHAR(T."PLANTA") AND DUP.LINEA = T."LINEA" AND DUP.FECHA = CAST(T."FECHA" AS DATE)
);

CREATE COLUMN TABLE "DBADMIN"."TMP_SANEO_PVC_STAGE2_20261124" AS (
SELECT Y."ID_REGISTRO", Y.OTMP, Y.OTMC,
       ROUND(Y.MP, 2) AS MP, ROUND(Y.MTTO, 2) AS MTTO, ROUND(Y.HERR, 2) AS HERR,
       ROUND(Y.TD_EXACTO, 2) AS TD, ROUND(Y.TP_EXACTO, 2) AS TP,
       ROUND(CASE WHEN Y.TP_EXACTO > 0 THEN (Y.PROD + Y.SCRAP) / Y.TP_EXACTO ELSE 0 END, 2) AS KGNETOS,
       ROUND(Y.TD_EXACTO * Y.KG_HR_PRODUCTO, 2) AS KG_POR_TD,
       ROUND(CASE WHEN Y.TP_EXACTO > 0 AND Y.KG_HR_PRODUCTO > 0
                  THEN ((Y.PROD + Y.SCRAP) / Y.TP_EXACTO) / Y.KG_HR_PRODUCTO * 100 ELSE 0 END, 2) AS REND,
       ROUND(CASE WHEN Y.TD_EXACTO > 0 THEN Y.TP_EXACTO / Y.TD_EXACTO * 100 ELSE 0 END, 2) AS DISP,
       ROUND(CASE WHEN Y.TD_EXACTO > 0 THEN Y.TP_EXACTO / Y.TD_EXACTO ELSE 0 END, 4) AS DISP_F,
       ROUND(CASE WHEN Y.TP_EXACTO > 0 AND Y.KG_HR_PRODUCTO > 0
                  THEN ((Y.PROD + Y.SCRAP) / Y.TP_EXACTO) / Y.KG_HR_PRODUCTO ELSE 0 END, 4) AS REND_F,
       ROUND(IFNULL(Y.CALIDAD, 0) / 100, 4) AS CAL_F,
       ROUND(CASE WHEN Y.TD_EXACTO * Y.KG_HR_PRODUCTO > 0
                  THEN Y.PROD / (Y.TD_EXACTO * Y.KG_HR_PRODUCTO) * 100 ELSE 0 END, 2) AS EFICIENCIA,
       Y.OLD_P, Y.MAP_P, Y.OLD_C, Y.MAP_C, Y.DUP_FILAS
FROM (
    SELECT S."ID_REGISTRO", S.OTMP, S.OTMC,
           S.MP_EXACTO AS MP, S.MTTO_EXACTO AS MTTO, S.HERR_EXACTO AS HERR,
           GREATEST(IFNULL(T."HORAS_PROGRAMADAS", 0)
                 - (S.MP_EXACTO + IFNULL(T."CONTROL_INVENTARIOS", 0) + IFNULL(T."FALTA_MATERIA_INSUMOS", 0)
                    + IFNULL(T."CAMBIO_MOLDE_HR", 0) + IFNULL(T."CALENTAMIENTO_HR", 0)
                    + IFNULL(T."PARO_ARRANQUE_NO_PROGRAMADO", 0) + IFNULL(T."ARRANQUE_ESTABILIZACION_HR", 0)), 0) AS TD_EXACTO,
           GREATEST(IFNULL(T."HORAS_PROGRAMADAS", 0)
                 - (S.MP_EXACTO + IFNULL(T."CONTROL_INVENTARIOS", 0) + IFNULL(T."FALTA_MATERIA_INSUMOS", 0)
                    + IFNULL(T."CAMBIO_MOLDE_HR", 0) + IFNULL(T."CALENTAMIENTO_HR", 0)
                    + IFNULL(T."PARO_ARRANQUE_NO_PROGRAMADO", 0) + IFNULL(T."ARRANQUE_ESTABILIZACION_HR", 0))
                 - (S.MTTO_EXACTO + S.HERR_EXACTO + IFNULL(T."FALLA_ELECTRICA", 0) + IFNULL(T."SERVICIOS", 0)
                    + IFNULL(T."CAMBIO_MOLDE_SETUP_EXCESOS", 0) + IFNULL(T."FALLA_OPERACION", 0)
                    + IFNULL(T."LIMPIEZA_TANQUE", 0) + IFNULL(T."FALTA_MATERIAL", 0)
                    + IFNULL(T."FALTA_PERSONAL", 0) + IFNULL(T."FALTA_REFACCIONES", 0)), 0) AS TP_EXACTO,
           IFNULL(T."PRODUCCION_NETA_REAL", 0) AS PROD, IFNULL(T."TOTAL_SCRAP_KG", 0) AS SCRAP,
           IFNULL(T."KG_HR_PRODUCTO", 0) AS KG_HR_PRODUCTO, T."PORCENTAJE_CALIDAD" AS CALIDAD,
           S.OLD_P, S.MAP_P, S.OLD_C, S.MAP_C, S.DUP_FILAS
    FROM "DBADMIN"."TMP_SANEO_PVC_STAGE_20261124" S
    JOIN "DBADMIN"."PdxMTTOTiemposMuertosProduccionPVC" T ON T."ID_REGISTRO" = S."ID_REGISTRO"
) Y
);

