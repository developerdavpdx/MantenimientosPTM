  AND IFNULL(LENGTH(TO_NVARCHAR(T."ID_PARO")), 0) = 0
  AND IFNULL(T."ORIGEN", 'MANUAL') = 'MANUAL'
  AND T."ID_PRODUCTO_TERMINADO" IS NULL AND T."PRODUCTO" IS NULL AND T."TURNO" IS NULL
