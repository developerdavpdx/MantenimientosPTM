                  THEN ((Y.PROD + Y.SCRAP) / Y.TP_EXACTO) / Y.KG_HR_PRODUCTO * 100 ELSE 0 END, 2) AS REND,
       ROUND(CASE WHEN Y.TD_EXACTO > 0 THEN Y.TP_EXACTO / Y.TD_EXACTO * 100 ELSE 0 END, 2) AS DISP,
       ROUND(CASE WHEN Y.TD_EXACTO > 0 THEN Y.TP_EXACTO / Y.TD_EXACTO ELSE 0 END, 4) AS DISP_F,
       ROUND(CASE WHEN Y.TP_EXACTO > 0 AND Y.KG_HR_PRODUCTO > 0
                  THEN ((Y.PROD + Y.SCRAP) / Y.TP_EXACTO) / Y.KG_HR_PRODUCTO ELSE 0 END, 4) AS REND_F,
       ROUND(IFNULL(Y.CALIDAD, 0) / 100, 4) AS CAL_F,
       ROUND(CASE WHEN Y.TD_EXACTO * Y.KG_HR_PRODUCTO > 0
                  THEN Y.PROD / (Y.TD_EXACTO * Y.KG_HR_PRODUCTO) * 100 ELSE 0 END, 2) AS EFICIENCIA,
       Y.OLD_P, Y.MAP_P, Y.OLD_C, Y.MAP_C, Y.DUP_FILAS
FROM (
    SELECT S."ID_REGISTRO", S.OTMP, S.OTMC,
           S.MP_EXACTO AS MP, S.MTTO_EXACTO AS MTTO, S.HERR_EXACTO AS HERR,
           GREATEST(IFNULL(T."HORAS_PROGRAMADAS", 0)
                 - (S.MP_EXACTO + IFNULL(T."CONTROL_INVENTARIOS", 0) + IFNULL(T."FALTA_MATERIA_PRIMA", 0)
                    + IFNULL(T."PREPARACION_LINEA", 0)), 0) AS TD_EXACTO,
           GREATEST(IFNULL(T."HORAS_PROGRAMADAS", 0)
                 - (S.MP_EXACTO + IFNULL(T."CONTROL_INVENTARIOS", 0) + IFNULL(T."FALTA_MATERIA_PRIMA", 0)
                    + IFNULL(T."PREPARACION_LINEA", 0))
                 - (S.MTTO_EXACTO + S.HERR_EXACTO + IFNULL(T."TIEMPO_MUERTO_ARRANQUES", 0)
                    + IFNULL(T."FALLA_MATERIAL", 0) + IFNULL(T."FALTA_PERSONAL", 0)
                    + IFNULL(T."FALLA_ELECTRICA", 0) + IFNULL(T."TIEMPO_MUERTO_PROCESO", 0)), 0) AS TP_EXACTO,
           IFNULL(T."PRODUCCION_NETA", 0) AS PROD, IFNULL(T."TOTAL_SCRAP", 0) AS SCRAP,
           IFNULL(T."KG_HR_PRODUCTO", 0) AS KG_HR_PRODUCTO, T."PORCENTAJE_CALIDAD" AS CALIDAD,
           S.OLD_P, S.MAP_P, S.OLD_C, S.MAP_C, S.DUP_FILAS
    FROM "DBADMIN"."TMP_SANEO_INY_STAGE_20261124" S
    JOIN "DBADMIN"."PdxMTTOTiemposMuertosProduccionINY" T ON T."ID_REGISTRO" = S."ID_REGISTRO"
) Y
);

