FROM "DBADMIN"."PdxMTTOTiemposMuertosProduccionPVC" TM
JOIN "DBADMIN"."PdxMTTOMPGenerados" MPG
  ON LOCATE(TO_NVARCHAR(TM."OTMP"), '"' || TRIM(MPG."NUMERO_ORDEN") || '"') > 0
LEFT JOIN "DBADMIN"."PdxMTTOOrdenesTrabajoMP" OT
  ON OT."NUMERO_ORDEN" = MPG."NUMERO_ORDEN"
WHERE IFNULL(TM."ESTATUS", 'A') = 'A'
  AND TM."FECHA" BETWEEN '2026-11-01' AND '2026-11-30'
  AND TO_NVARCHAR(TM."OTMP") LIKE '%OTMP-%'
);

