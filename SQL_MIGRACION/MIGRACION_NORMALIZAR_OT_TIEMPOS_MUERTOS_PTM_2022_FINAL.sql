MERGE INTO "PTM_2022_FINAL"."PdxMTTOTiemposMuertosProduccionPVC" T
USING (
    SELECT ID_REGISTRO,
           '["' || STRING_AGG(TOKEN, '","' ORDER BY TOKEN) || '"]' AS VALOR_NUEVO
    FROM (
        SELECT DISTINCT T2."ID_REGISTRO",
               SUBSTRING_REGEXPR('OTMC-[A-Za-z0-9_-]+' IN T2."OTMC" OCCURRENCE S.ELEMENT_NUMBER) AS TOKEN
        FROM "PTM_2022_FINAL"."PdxMTTOTiemposMuertosProduccionPVC" T2
        CROSS JOIN SERIES_GENERATE_INTEGER(1, 1, 100) S
        WHERE T2."OTMC" IS NOT NULL
          AND SUBSTRING_REGEXPR('OTMC-[A-Za-z0-9_-]+' IN T2."OTMC" OCCURRENCE S.ELEMENT_NUMBER) IS NOT NULL
    ) Q
    GROUP BY ID_REGISTRO
) X
ON T."ID_REGISTRO" = X.ID_REGISTRO
WHEN MATCHED THEN UPDATE SET T."OTMC" = X.VALOR_NUEVO;

